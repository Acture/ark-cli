use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
	let manifest_dir: PathBuf =
		PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
	let schema_dir: PathBuf = manifest_dir.join("schema");
	let out_dir: PathBuf =
		PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("verification_artifact");

	fs::create_dir_all(&out_dir).expect("create FlatBuffer output directory");
	println!("cargo:rerun-if-changed={}", schema_dir.display());
	println!("cargo:rerun-if-changed=build.rs");

	let mut schemas: Vec<PathBuf> = fs::read_dir(&schema_dir)
		.expect("read strategy schema directory")
		.filter_map(|entry| entry.ok().map(|entry| entry.path()))
		.filter(|path| path.extension().and_then(|extension| extension.to_str()) == Some("fbs"))
		.collect();
	schemas.sort();
	assert!(
		!schemas.is_empty(),
		"no strategy FlatBuffer schemas found in {}",
		schema_dir.display()
	);

	for schema in &schemas {
		generate_schema(schema, &out_dir);
	}

	let mut modules: Vec<String> = schemas
		.iter()
		.filter_map(|schema| schema.file_stem().and_then(|stem| stem.to_str()))
		.map(|stem| {
			let generated: PathBuf = out_dir.join(format!("{stem}_generated.rs"));
			format!(
				"#[path = {:?}]\npub mod {stem};",
				generated.display().to_string()
			)
		})
		.collect();
	modules.sort();
	fs::write(
		out_dir.join("mod.rs"),
		format!(
			"// Generated by build.rs; do not edit.\n{}\n",
			modules.join("\n")
		),
	)
	.expect("write generated module index");
}

fn generate_schema(schema: &Path, out_dir: &Path) {
	let output = Command::new("flatc")
		.arg("--rust")
		.arg("--gen-object-api")
		.arg("-o")
		.arg(out_dir)
		.arg(schema)
		.output()
		.unwrap_or_else(|error| {
			panic!(
				"failed to invoke flatc for {}: {error}. Install it with `brew install flatbuffers`",
				schema.display()
			)
		});
	if !output.status.success() {
		panic!(
			"flatc failed for {}: {}",
			schema.display(),
			String::from_utf8_lossy(&output.stderr)
		);
	}
}
